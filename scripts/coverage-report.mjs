#!/usr/bin/env node
/** Regenerates docs/DATA-COVERAGE.md from the actual contents of public/data. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (n) => JSON.parse(readFileSync(resolve(root, 'public/data', n), 'utf8'));
const items = read('items.json');
const recipes = read('recipes.json');
const professions = read('professions.json');
const manifest = read('data-manifest.json');

const itemIds = new Set(items.map((i) => i.id));
const count = (arr, pred) => arr.filter(pred).length;
const verified = count(recipes, (r) => r.verification === 'verified');
const dangling = recipes.filter(
  (r) => !itemIds.has(r.outputItemId) || r.ingredients.some((g) => !itemIds.has(g.itemId)),
).length;
const withProfession = count(recipes, (r) => r.professionId);
const mismatches = [];
if (manifest.itemCount !== items.length) mismatches.push('itemCount');
if (manifest.recipeCount !== recipes.length) mismatches.push('recipeCount');
if (manifest.verifiedRecipeCount !== verified) mismatches.push('verifiedRecipeCount');

const md = `# Data coverage report

Generated by \`npm run coverage\` from \`public/data/*.json\`. Do not edit by hand.

| Metric | Value |
|---|---|
| Data version | ${manifest.dataVersion} |
| Source | ${manifest.sourceUrl} |
| Import date | ${manifest.importDate ?? 'never imported'} |
| Items | ${items.length} |
| Recipes | ${recipes.length} |
| Professions | ${professions.length} |
| Verified recipes | ${verified} |
| Unverified recipes | ${recipes.length - verified} |
| Recipes with profession info | ${withProfession} |
| Recipes referencing unknown items | ${dangling} |
| Manifest/data count mismatches | ${mismatches.length ? mismatches.join(', ') : 'none'} |

Verification status: **${manifest.verificationStatus}**

## Known limitations

${manifest.knownLimitations.map((l) => `- ${l}`).join('\n')}

${recipes.length === 0 ? `## Honest summary

**0 recipes are bundled.** Aion2.gg forbids bulk downloading and dataset building in its Terms of Use
(https://aion2.gg/terms) and disallows \`/api/\` and \`/data-dump/\` in robots.txt, so no data was scraped
and none was invented. No coverage of the Global recipe list is claimed.
` : ''}`;
writeFileSync(resolve(root, 'docs/DATA-COVERAGE.md'), md);
console.log(md);
